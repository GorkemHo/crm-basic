using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;

namespace CRM.Modules.Attachments.Infrastructure.Storage;

internal sealed class AttachmentOptions
{
    public const string SectionName = "Attachments";

    /// <summary>Folder for the files; relative paths are under the app's content root. Back it up with the database.</summary>
    public string StoragePath { get; set; } = "App_Data/attachments";

    public int MaxFileSizeMb { get; set; } = 20;

    /// <summary>
    /// Allowed extensions (lower case, with the dot). Anything a browser could run or render as a page
    /// (.html, .svg, .js, executables...) is deliberately not in the default list.
    /// </summary>
    public string[] AllowedExtensions { get; set; } =
    [
        ".pdf", ".txt", ".csv", ".rtf",
        ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx", ".odt", ".ods", ".odp",
        ".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp",
        ".zip", ".7z", ".rar",
        ".eml", ".msg"
    ];

    public long MaxFileSizeBytes => MaxFileSizeMb * 1024L * 1024L;
}

/// <summary>Where attachment bytes are kept. Keys are generated by the store; callers never pass paths.</summary>
internal interface IFileStorage
{
    /// <returns>The key to read or delete the file with.</returns>
    Task<string> SaveAsync(Stream content, CancellationToken cancellationToken);

    Stream OpenRead(string key);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

/// <summary>Files on the server's disk, spread over sub-folders by the first characters of their key.</summary>
internal sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(IOptions<AttachmentOptions> options, IHostEnvironment environment)
    {
        _root = Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.Value.StoragePath));
    }

    public async Task<string> SaveAsync(Stream content, CancellationToken cancellationToken)
    {
        var key = $"{Guid.NewGuid():N}";
        var path = PathOf(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, cancellationToken);

        return key;
    }

    public Stream OpenRead(string key) =>
        new FileStream(PathOf(key), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);

    public Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        var path = PathOf(key);
        if(File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    private string PathOf(string key)
    {
        // Keys are 32 hex characters made here; anything else is a bug or tampering.
        if(key.Length != 32 || !key.All(Uri.IsHexDigit))
        {
            throw new ArgumentException("Invalid storage key.", nameof(key));
        }

        return Path.Combine(_root, key[..2], key);
    }
}
